local _, ns = ...

local locales = ns and ns.Locales
if type(locales) ~= "table" then
    return
end

local function apply(locale, entries)
    if type(locale) ~= "table" or type(entries) ~= "table" then
        return
    end

    for key, value in pairs(entries) do
        locale[key] = value
    end
end

