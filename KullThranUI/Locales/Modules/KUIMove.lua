local function fillMissing(locale, entries)
    if not locale then return end
    for key, value in pairs(entries) do
        local current = rawget(locale, key)
        local placeholder = current == nil
            or current == key
            or current == rawget(locales.enUS or {}, key)
        if not placeholder and type(current) == "string" then
            if key:sub(1, 5) == "BAGS_" then
                placeholder = current:find("_", 1, true) ~= nil
                    or current:match("^[A-Z0-9_ %%+%-]+$") ~= nil
            elseif key:sub(1, 7) == "RELOAD_" or key:sub(1, 6) == "RESET_" then
                placeholder = current:find("_", 1, true) ~= nil
            end
        end
        if placeholder then
            locale[key] = value
        end
    end
end

