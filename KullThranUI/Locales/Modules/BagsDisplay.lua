local function Apply(target, locale)
    if type(target) ~= "table" then return end
    local translated = values[locale] or values.enUS
    for index, key in ipairs(keys) do
        -- rawget: the locale tables fall back to English through __index.
        local current = rawget(target, key)
        if current == nil or current == key then
            target[key] = translated[index] or values.enUS[index]
        end
    end
end

for _, locale in ipairs({ "enUS", "esES", "deDE", "frFR", "itIT", "ptBR", "ruRU", "koKR", "zhCN", "zhTW" }) do
    Apply(locales[locale], locale)
end
if locales.esMX and locales.esMX ~= locales.esES then Apply(locales.esMX, "esES") end
