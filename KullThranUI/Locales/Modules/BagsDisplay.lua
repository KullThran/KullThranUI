local function ApplyToolbar(target, locale)
    if type(target) ~= "table" then return end
    local translated = toolbarValues[locale] or toolbarValues.enUS
    for index, key in ipairs(toolbarKeys) do
        -- rawget: the locale tables fall back to English through __index.
        local current = rawget(target, key)
        if current == nil or current == key then
            target[key] = translated[index] or toolbarValues.enUS[index]
        end
    end
end

for _, locale in ipairs({ "enUS", "esES", "deDE", "frFR", "itIT", "ptBR", "ruRU", "koKR", "zhCN", "zhTW" }) do
    ApplyToolbar(locales[locale], locale)
end
if locales.esMX and locales.esMX ~= locales.esES then ApplyToolbar(locales.esMX, "esES") end
if locales.ptPT and locales.ptPT ~= locales.ptBR then ApplyToolbar(locales.ptPT, "ptBR") end
