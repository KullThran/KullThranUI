for _, entries in ipairs({ BASE, FIXES }) do
for key, byLocale in pairs(entries) do
    for locale, value in pairs(byLocale) do
        local target = locales[locale]
        if type(target) == "table" then target[key] = value end
        -- The sibling locales share these tables when the client has them.
        if locale == "esES" and type(locales.esMX) == "table" and locales.esMX ~= target then locales.esMX[key] = value end
        if locale == "ptBR" and type(locales.ptPT) == "table" and locales.ptPT ~= target then locales.ptPT[key] = value end
    end
end
